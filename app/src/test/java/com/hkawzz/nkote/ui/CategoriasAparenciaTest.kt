/** Categorias com ícone e cor pela interface (v0.4, C2). Dados fictícios. */
@RunWith(AndroidJUnit4::class)
@GraphicsMode(GraphicsMode.Mode.NATIVE)
@Config(qualifiers = "w411dp-h891dp-xxhdpi")
class CategoriasAparenciaTest {
    @get:Rule val regra = createComposeRule()
    private lateinit var banco: NkPayBanco
    private lateinit var container: AppContainer

    @Before
    fun abrir() {
        banco = Room.inMemoryDatabaseBuilder(ApplicationProvider.getApplicationContext<Context>(), NkPayBanco::class.java).build()
        container = AppContainer(banco, RelogioFalso())
        runBlocking { container.categorias.garantirCategoriasIniciais() }
    }

    @After fun fechar() = banco.close()

    private fun esperar(texto: String) = regra.waitUntil(10_000) { regra.onAllNodes(hasText(texto)).fetchSemanticsNodes().isNotEmpty() }
    private fun foto(nome: String) { regra.waitForIdle(); regra.onRoot().captureRoboImage("build/outputs/roborazzi/$nome.png") }

    @Test
    fun trocarIconeECorDeUmaCategoria() {
        regra.setContent { NkPayTema { CompositionLocalProvider(LocalContainer provides container) { NkPayApp() } } }
        regra.onNodeWithText("Mais").performClick()
        regra.onNodeWithText("Categorias").performClick()
        esperar("Em uso")
        foto("c2-categorias")

        regra.onNodeWithText("Moradia").performClick()
        esperar("Editar categoria")
        regra.onNodeWithContentDescription("Ícone Água").performScrollTo().performClick()
        foto("c2-editar-categoria")
        regra.onNodeWithText("Salvar").performScrollTo().performClick()
        esperar("Em uso")

        regra.waitUntil(10_000) { runBlocking { container.categorias.observar().first() }.first { it.nome == "Moradia" }.icone == "agua" }
        assertEquals("agua", runBlocking { container.categorias.observar().first() }.first { it.nome == "Moradia" }.icone)
    }
}
